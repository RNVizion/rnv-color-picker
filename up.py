def step_header() -> None:
    """Replace exactly the eight brand assignments and their docstrings.

    Bounded by the AST, not by scanning for a comment banner. The first
    draft of this walked forward until it found a line starting with a
    banner character, and when the palettes below were not preceded by one
    it swallowed them to end of file -- deleting all three theme dicts and
    then reporting step 1 successful. A parser knows where a statement
    ends; a string search only knows what it happened to find next.
    """
    src, mode = read_any(CONFIG)
    lines = src.splitlines(keepends=True)
    tree = ast.parse(src)

    spans = []
    body = tree.body
    for i, node in enumerate(body):
        name = None
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            name = node.target.id
        elif isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
        if name not in BRAND_BLOCK:
            continue
        end = node.end_lineno
        # a bare string statement immediately after is that constant's
        # docstring and belongs to the span
        if (i + 1 < len(body) and isinstance(body[i + 1], ast.Expr)
                and isinstance(body[i + 1].value, ast.Constant)
                and isinstance(body[i + 1].value.value, str)):
            end = body[i + 1].end_lineno
        spans.append((node.lineno, end, name))

    missing = set(BRAND_BLOCK) - {n for _, _, n in spans}
    if missing:
        die(f"these brand constants were not found as module-level "
            f"assignments in utils/config.py: {sorted(missing)}. "
            f"Nothing changed.")

    first = min(s for s, _, _ in spans)
    last = max(e for _, e, _ in spans)

    # Refuse to proceed if the span is implausibly large -- a guard against
    # exactly the failure described above.
    if last - first > 80:
        die(f"the brand block spans {last - first} lines, which is far more "
            f"than the eight declarations should occupy. Refusing to "
            f"replace it. Nothing changed.")

    new = "".join(lines[:first - 1]) + NEW_HEADER + "".join(lines[last:])
    ast.parse(new)          # never write a file that will not parse
    write_any(CONFIG, new, mode)
    say(f"step 1: brand header rewritten, lines {first}-{last} "
        f"-- 6 literals now derived", OK)


