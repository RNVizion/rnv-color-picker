RETIRED = {
    OLD_GOLD: "the app-local dark gold",
    "#c4a458": "the orphaned lighter light-mode hover",
    "#8a7236": "the hand-written light-mode pressed",
    "#dcc9a3": "the hand-written dark hover",
    "#b7a480": "the hand-written dark pressed, a third gold serving one key",
    "#4caf50": "Material success",
    "#f44336": "Material error",
    OLD_TAB_HOVER: "the tab hover ground no gold cleared",
}


def verify() -> bool:
    ok = True
    for m in [k for k in list(sys.modules) if k.startswith("utils")]:
        del sys.modules[m]
    sys.path.insert(0, str(REPO))
    from utils import config as C  # noqa: E402

    tree = ast.parse(read_any(CONFIG)[0])
    assigns = {}
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            assigns[node.target.id] = node.value
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    assigns[t.id] = node.value
    # Computed from a call ...
    for name in ("BRAND_DARK_GOLD_DEEP", "BRAND_GOLD_HOVER",
                 "BRAND_GOLD_RGB", "BRAND_DARK_GOLD_RGB"):
        if not isinstance(assigns.get(name), ast.Call):
            ok = False
            say(f"verify: {name} should be computed and is not", FAIL)
    # ... or an alias of another constant. Both count as derived; what is
    # forbidden is a written-down literal, which stops tracking its source.
    for name in ("BRAND_GOLD_PRESSED", "BRAND_DARK_GOLD_PRESSED",
                 "BRAND_DARK_GOLD_HOVER"):
        if not isinstance(assigns.get(name), ast.Name):
            ok = False
            say(f"verify: {name} should alias another constant and does not",
                FAIL)
    for name, expect in (("BRAND_DARK_GOLD_DEEP", DEEP_GOLD),
                         ("BRAND_GOLD_HOVER", "#dfc9a0"),
                         ("BRAND_GOLD_PRESSED", "#d2bc93")):
        got = getattr(C, name, None)
        if got != expect:
            ok = False
            say(f"verify: {name} computed to {got}, expected {expect}", FAIL)

    # The guard file is brand new on a first run, so git does not track it
    # yet. Counting only tracked files would report zero guards and fail a
    # correct run.
    scan = list(tracked(".py", ".md", ".json"))
    guard_path = REPO / GUARD_TEST_PATH
    if guard_path.exists() and guard_path not in scan:
        scan.append(guard_path)
    guards = 0
    stale = []
    for path in scan:
        text = read_any(path)[0]
        if GUARD_MARKER in text:
            guards += 1
            continue
        for i, line in enumerate(text.splitlines(), 1):
            if MENTION.search(line):
                continue
            for value, what in RETIRED.items():
                if value in line.lower():
                    stale.append(f"{path.relative_to(REPO)}:{i}: {what} "
                                 f"({value}) -- {line.strip()[:52]}")
            if OLD_SYM in line:
                stale.append(f"{path.relative_to(REPO)}:{i}: old symbol")
    if stale:
        ok = False
        say("verify: retired values still present:", FAIL)
        for s in stale:
            say(f"        {s}", FAIL)
    if guards != 1:
        ok = False
        say(f"verify: expected exactly one guard file carrying the marker, "
            f"found {guards}", FAIL)

    # Import every module this pass edited, in a subprocess. A missing
    # import is a NameError on a code path no unit test may reach, and the
    # first draft of this script shipped exactly that -- the edit that adds
    # the import silently did not match, and nothing said so until the full
    # suite ran a widget that happened to hit the line.
    probe = ("import os; os.environ.setdefault('QT_QPA_PLATFORM','offscreen')\n"
             "from PyQt6.QtWidgets import QApplication\n"
             "QApplication.instance() or QApplication([])\n"
             "import utils.config, utils.cache, ui.settings_panel\n"
             "from ui.settings_panel import SettingsPanel\n"
             "assert hasattr(SettingsPanel, '_get_accent_text')\n")
    r = subprocess.run([sys.executable, "-c", probe], cwd=REPO,
                       capture_output=True, text=True,
                       env=dict(os.environ, QT_QPA_PLATFORM="offscreen"))
    if r.returncode != 0:
        ok = False
        say("verify: an edited module does not import cleanly:", FAIL)
        for line in r.stderr.strip().splitlines()[-6:]:
            say(f"        {line}", FAIL)

    say("verify: pairing audit delegated to the guard suite")
    say("verify: PASS" if ok else "verify: FAIL", OK if ok else FAIL)
    return ok


PYTEST_EXIT = {
    0: ("all tests passed", OK),
    1: ("tests FAILED -- see above", FAIL),
    2: ("the run was interrupted before it finished", WARN),
    3: ("pytest hit an internal error", WARN),
    4: ("pytest usage error", WARN),
    5: ("NO TESTS RAN. That is not a pass.", FAIL),
}


def classify(code: int) -> str:
    return "killed" if code < 0 else ("pass" if code == 0 else "fail")


def run_guard_tests() -> str:
    env = dict(os.environ, QT_QPA_PLATFORM="offscreen")
    say(f"running the guard suite ({GUARD_TEST_PATH}) ...")
    r = subprocess.run([sys.executable, "-m", "pytest", "-q", GUARD_TEST_PATH],
                       cwd=REPO, env=env, capture_output=True, text=True)
    for line in (r.stdout + r.stderr).strip().splitlines()[-8:]:
        say(f"    {line}")
    return classify(r.returncode)


def run_suite(quick: bool = False) -> str:
    env = dict(os.environ, QT_QPA_PLATFORM="offscreen")
    cmd = [sys.executable, "-m", "pytest", "-q"]
    if quick:
        cmd += ["-m", "not benchmark"]
    say("running the full test suite ...")
    r = subprocess.run(cmd, cwd=REPO, env=env, capture_output=True, text=True)
    out = (r.stdout + r.stderr).strip().splitlines()
    keep = [ln for ln in out if ln.startswith(("FAILED", "ERROR"))
            or " failed" in ln or " passed" in ln]
    for line in (keep or out)[-15:]:
        say(f"    {line}")
    if r.returncode < 0:
        sig = -r.returncode
        name = {9: "SIGKILL -- out of memory",
                15: "SIGTERM -- something asked it to stop; on a codespace "
                    "driven from a browser this is\n         usually the "
                    "session being reclaimed, not the tests"}.get(
                        sig, f"signal {sig}")
        say(f"\n    the test process was KILLED by {name}", WARN)
        say(f"    Not a test result. Your CI runs the full suite on every "
            f"push; that is the authority.", WARN)
        return "killed"
    msg, colour = PYTEST_EXIT.get(r.returncode,
                                  (f"pytest exited {r.returncode}", WARN))
    say(f"\n    {msg}", colour)
    return classify(r.returncode)


def remove_helpers(extra: list[str]) -> None:
    doomed = [p for p in tracked(".py", ".sh", ".md")
              if TOOL_MARKER in p.read_text(encoding="utf-8", errors="ignore")]
    if SELF.exists() and SELF not in doomed:
        doomed.append(SELF)
    for name in extra:
        p = (REPO / name).resolve()
        if not p.exists():
            say(f"    {name}: not here, nothing to remove", WARN)
        elif p not in doomed:
            doomed.append(p)
    for p in sorted(set(doomed)):
        try:
            p.unlink()
            say(f"    removed {p.relative_to(REPO)}", OK)
        except OSError as exc:
            say(f"    could NOT remove {p.relative_to(REPO)}: {exc}", FAIL)

    st = subprocess.run(["git", "status", "--porcelain"], cwd=REPO,
                        capture_output=True, text=True).stdout.splitlines()
    mod = sorted(ln[3:] for ln in st if ln[:2].strip() in ("M", "??"))
    dele = sorted(ln[3:] for ln in st if ln[:2].strip() == "D")
    parts = []
    if mod:
        parts.append("align brand gold, derive variants, consolidate status")
    if dele:
        parts.append("drop " + ", ".join(dele[:3]))
    say("\n    Working tree is ready. One commit takes everything:", OK)
    say("      git add -A")
    say(f"      git commit -m '{'; '.join(parts) or 'no changes'}'")
    say("      git push")


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Brand alignment for rnv-color-picker.")
    ap.add_argument("--verify-only", action="store_true")
    ap.add_argument("--install-deps", action="store_true",
                    help="apt-get the Qt system libraries, then continue")
    ap.add_argument("--refresh-guards", action="store_true")
    ap.add_argument("--finish", nargs="*", metavar="FILE",
                    help="verify, run the guard suite, then delete this tool "
                         "and any extra FILEs. Deletion only if all passed.")
    ap.add_argument("--skip-tests", action="store_true",
                    help="skip the full suite; the guard suite always runs")
    ap.add_argument("--quick-tests", action="store_true")
    args = ap.parse_args()

    if args.install_deps:
        install_system_deps()
    if args.refresh_guards or args.finish is not None:
        step_guard_tests()

    if not (args.verify_only or args.refresh_guards
            or args.finish is not None):
        preflight()
        step_header()
        step_sweep()
        step_light_palette()
        step_error_text_key()
        step_status()
        step_about_accent()
        step_accent_split()
        step_legacy_assertions()
        step_guard_tests()

    ok = verify()
    if run_guard_tests() != "pass":
        ok = False

    if args.finish is not None:
        if not args.skip_tests and run_suite(args.quick_tests) == "fail":
            ok = False
        if ok:
            say("\nremoving transfer helpers ...")
            remove_helpers(args.finish)
        else:
            say("\nNOT removing anything -- the checks did not pass. The "
                "tools stay so you can find out why.", FAIL)
    elif not args.skip_tests:
        if run_suite(args.quick_tests) == "fail":
            ok = False

    say("\nDONE -- all checks passed" if ok
        else "\nDONE -- with failures above", OK if ok else FAIL)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
