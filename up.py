def _dict_span(src: str, name: str) -> tuple[int, int]:
    """Character span of a module-level dict assignment, found by parsing.

    Not str.index. The module docstring of utils/config.py names all three
    palettes in a sentence, so a search for "LIGHT_THEME_COLORS" lands in
    prose thirty lines above the dict and every subsequent edit silently
    matches nothing. Same failure as the header block: a string search only
    knows what it happened to find first.
    """
    tree = ast.parse(src)
    for node in tree.body:
        target = None
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            target = node.target.id
        elif isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            target = node.targets[0].id
        if target != name:
            continue
        lines = src.splitlines(keepends=True)
        start = sum(len(x) for x in lines[:node.lineno - 1])
        end = sum(len(x) for x in lines[:node.end_lineno])
        return start, end
    die(f"{name} is not a module-level assignment in utils/config.py")
    raise SystemExit(1)          # unreachable, keeps type checkers happy


