MENTION = re.compile(
    r"\b(was|were|previously|formerly|used to|replaced|retired|legacy|"
    r"deprecated|old value|superseded|orphaned|hand-written)\b", re.I)


def read_any(path: Path) -> tuple[str, str]:
    """Read a file that may not be plain UTF-8, losslessly.

    Two things in this repository break a naive read_text. utils/config.py
    carries a UTF-8 BOM, which stays in the string as U+FEFF and makes
    ast.parse reject the file outright. And core/palette_formats.py carries
    a cp1252 dash (byte 0x97), which raises on decode.

    Skipping either would be a silent hole in the sweep, and guessing an
    encoding would rewrite bytes this change never intended to touch. The
    BOM is stripped for processing and restored on write; undecodable bytes
    round-trip through surrogateescape exactly. Files come back
    byte-for-byte identical apart from the replacement itself.

    Returns the text and a tag naming how to write it back.
    """
    raw = path.read_bytes()
    bom = raw.startswith(b"\xef\xbb\xbf")
    try:
        text = raw.decode("utf-8-sig" if bom else "utf-8")
        return text, ("bom" if bom else "plain")
    except UnicodeDecodeError:
        return raw.decode("utf-8", errors="surrogateescape"), "surrogate"


def write_any(path: Path, text: str, mode: str) -> None:
    if mode == "bom":
        path.write_bytes(b"\xef\xbb\xbf" + text.encode("utf-8"))
    elif mode == "surrogate":
        with open(path, "w", encoding="utf-8", errors="surrogateescape") as fh:
            fh.write(text)
    else:
        path.write_text(text, encoding="utf-8")


def step_sweep() -> None:
    changed, held, odd = 0, [], []
    for path in tracked(".py", ".md"):
        src, mode = read_any(path)
        if mode == "surrogate":
            odd.append(str(path.relative_to(REPO)))
        if GUARD_MARKER in src:
            continue
        if OLD_SYM not in src and OLD_GOLD not in src.lower():
            continue
        out, touched = [], False
        for i, line in enumerate(src.splitlines(keepends=True), 1):
            if MENTION.search(line) and (OLD_SYM in line
                                         or OLD_GOLD in line.lower()):
                held.append(f"{path.relative_to(REPO)}:{i}: {line.strip()[:64]}")
                out.append(line)
                continue
            new = re.sub(re.escape(OLD_GOLD), NEW_GOLD,
                         line.replace(OLD_SYM, NEW_SYM), flags=re.I)
            touched |= new != line
            out.append(new)
        if touched:
            write_any(path, "".join(out), mode)
            changed += 1
    say(f"step 2: symbol + value swept across {changed} files", OK)
    for h in held:
        say(f"        held (reads as history, not current state): {h}", WARN)
    for o in odd:
        say(f"        read with surrogateescape (not UTF-8, bytes preserved): "
            f"{o}", WARN)


