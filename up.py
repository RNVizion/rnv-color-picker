FAIL, OK, WARN, OFF = "\033[31m", "\033[32m", "\033[33m", "\033[0m"


def say(msg: str, colour: str = "") -> None:
    print(f"{colour}{msg}{OFF}" if colour else msg)


def die(msg: str) -> None:
    say(f"ABORT: {msg}", FAIL)
    sys.exit(1)


def tracked(*suffixes: str) -> list[Path]:
    """Files git tracks, minus this tool and minus any guard file.

    Not a glob. A glob picks up scratch, virtualenvs, and this script --
    and a sweep that rewrites its own OLD_GOLD constant into the new gold
    destroys its definition of what it is hunting for. Exclusion is by
    content marker, so renaming the file cannot defeat it.
    """
    r = subprocess.run(["git", "ls-files", "-z"], cwd=REPO,
                       capture_output=True, text=True)
    if r.returncode != 0:
        die("git ls-files failed -- run this inside the repository.")
    out = []
    for name in r.stdout.split("\0"):
        if not name:
            continue
        p = (REPO / name).resolve()
        if p == SELF or not p.exists():
            continue
        if suffixes and p.suffix not in suffixes:
            continue
        if p.suffix == ".py":
            try:
                if TOOL_MARKER in p.read_text(encoding="utf-8", errors="ignore"):
                    continue
            except OSError:
                pass
        out.append(p)
    return sorted(out)


def _lum(h: str) -> float:
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    ch = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    ch = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in ch]
    return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]


def contrast(a: str, b: str) -> float:
    l1, l2 = sorted([_lum(a), _lum(b)], reverse=True)
    return (l1 + 0.05) / (l2 + 0.05)


